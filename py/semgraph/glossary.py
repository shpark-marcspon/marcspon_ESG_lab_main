def text(synonyms=False):
    rows = ["[ESG 공시 기준 — 주제 번호·이름·공시 항목(문서와 무관)]"]
    rows += [f"- {a}: {b}" for a, b in GRI + STANDARDS]
    if synonyms:
        rows += ["", "[ESG 용어 — 같은 것을 가리키는 다른 이름]"] + [f"- {a}: {b}" for a, b in SYNONYMS]
    return "\n".join(rows)


def contrary_text():
    return "\n".join(f"  · {a}: {b}" for a, b in CONTRARY)
